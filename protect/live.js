// 운영 주소에서 출처 안내가 실제로 보이는지 확인 (0.5.2, 회원 검토 치명 2).
// 내 컴퓨터의 빌드 결과만 보면, 서버가 다시 빌드해 안내가 사라진 운영 사이트도 '있음'으로 통과하고
// 반대로 운영에는 있는데 '없음'이 뜬다. --url 이 있으면 그 주소에서 직접 받아 본다(읽기만, 바꾸지 않는다).
import { fetchChecked, assetUrls } from './compare.js';
import { JS_HEADER_PREFIX } from './provenance-text.js';

const TIMEOUT_MS = 8000;
const TOTAL_MS = 30000;

// 반환: { ok, reason?, url, html, footer, llms, llmsOurs, robotsBlock, tdm, usage, dormsJson, jsHeader, jsChecked }
export async function fetchLiveProvenance(url, { allowLocal = false, fetchImpl, lookupImpl, provenanceId = '' } = {}) {
  const deadline = Date.now() + TOTAL_MS;
  const get = h => fetchChecked(h, { allowLocal, fetchImpl, lookupImpl, deadline, requestTimeoutMs: TIMEOUT_MS });
  let base;
  try { base = new URL(url); } catch { return { ok: false, reason: 'bad url' }; }
  const page = await get(base.href);
  if (!page.ok) return { ok: false, reason: page.error || 'network', url: base.href };
  if (page.status >= 400) return { ok: false, reason: `HTTP ${page.status}`, url: base.href };
  const finalBase = (() => { try { return new URL(page.finalUrl || base.href); } catch { return base; } })();
  const body = page.body || '';
  const ok200 = async p => {
    const r = await get(new URL(p, finalBase).href);
    return r.ok && r.status === 200 && typeof r.body === 'string' ? r.body : null;
  };
  const llms = await ok200('/llms.txt');
  const robots = await ok200('/robots.txt');
  const tdm = await ok200('/.well-known/tdmrep.json');
  const usage = await ok200('/usage.html');
  const dormsJson = await ok200('/dorms.json');
  // HTML 이 SPA 대체 화면(모든 주소에 같은 index.html)일 수 있어, 각 파일은 '그 파일다운지'로 판정한다.
  const looksHtml = s => /<html[\s>]|<!doctype html/i.test(s || '');
  let jsHeader = false, jsChecked = 0;
  for (const a of assetUrls(body, finalBase).slice(0, 6)) {
    const r = await get(a);
    if (!r.ok || r.status !== 200 || !r.body) continue;
    jsChecked++;
    if (r.body.slice(0, 4000).includes(JS_HEADER_PREFIX)) { jsHeader = true; break; }
  }
  return {
    ok: true,
    url: finalBase.href,
    html: body.includes('dorms-check:notice') || body.includes('data-dorms-check-notice') || (provenanceId && body.includes(provenanceId)),
    footer: body.includes('data-dorms-check-source'),
    llms: Boolean(llms) && !looksHtml(llms),
    llmsOurs: Boolean(llms) && llms.includes('generated by dorms-check'),
    robotsBlock: Boolean(robots) && robots.includes('# dorms-check'),
    tdm: Boolean(tdm) && !looksHtml(tdm),
    usage: Boolean(usage) && usage.includes('dorms-check-provenance'),
    dormsJson: Boolean(dormsJson) && dormsJson.includes('dorms-check provenance'),
    jsHeader,
    jsChecked,
  };
}
